'use strict';
const assert = require('assert/strict');
const a = require('../server/lib/answers');
assert(a.matches([2, 0], [0, 2]));
assert(!a.matches([0], [0, 2]));
assert(!a.matches([0, 1, 2], [0, 2]));
assert(!a.matches([0, 0], [0, 2]));
assert(a.matches(1, 1));
assert(!a.answered([]));
assert(!a.answered(-1));
assert(a.answered([0, 2]));
assert(a.includes([0, 2], 2));
assert.equal(a.normalize([0, 8], 4, true), null);
assert.equal(a.normalize([0, 0], 4, true), null);
assert.equal(a.normalize([], 4, true), null);
assert.equal(a.normalize([0], 4, false), null);
assert.deepEqual(a.normalize([2, 0], 4, true), [0, 2]);
assert.equal(a.format([0, 2], ['甲', '乙', '丙']), 'A. 甲；C. 丙');
console.log('PASS: multi-answer matching, validation, legacy answers, statistics and export formatting');
