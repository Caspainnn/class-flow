// Run: node server/grade/homework-page.check.cjs (no server or data access).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(__dirname + '/public/homework.html', 'utf8');
const script = html.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
const elements = new Map();
const element = id => { if (!elements.has(id)) elements.set(id, {textContent:'',value:'',innerHTML:'',classList:{toggle(){}},disabled:false,open:false,addEventListener(){},querySelectorAll(){return []},showModal(){this.open=true},close(){this.open=false}}); return elements.get(id); };
const ctx = vm.createContext({ URLSearchParams, document: { getElementById: element }, location: { search: '' } });
vm.runInContext(script.replace(/init\(\);\s*$/, ''), ctx);
assert.equal(vm.runInContext(`esc("<a title='x'>&")`, ctx), '&lt;a title=&#39;x&#39;&gt;&amp;');
assert.equal(vm.runInContext(`scoreText({a:{score:88,st:'late'},b:{score:0,st:'ok'},c:{st:'no'}})`, ctx), 'a 88 补\nb 0\nc 未交');
assert.equal(vm.runInContext(`analysisURL({courseId:'c&x',id:'h?x'})`, ctx), '/xueqing?tab=prac&courseId=c%26x&homeworkId=h%3Fx');
assert.equal(vm.runInContext(`statusText({mode:'manual',published:false,submitted:0})`, ctx), '待处理');
assert.equal(vm.runInContext(`statusText({mode:'file',status:'running'})`, ctx), '批改中');
assert.equal(vm.runInContext(`dueInputType('11/28')`, ctx), 'text');
assert.equal(vm.runInContext(`dueInputType('2026-11-28')`, ctx), 'date');
assert.equal(vm.runInContext(`dueInputType('')`, ctx), 'date');
assert.match(html, /data-active="hw-list"/);
assert.doesNotMatch(script, /\b(?:alert|confirm|prompt)\s*\(/);
assert.doesNotMatch(html, /\son(?:click|submit|change)=/);
async function main() {
  const requests = [];
  ctx.fetch = async (url, opts) => {
    requests.push({url,opts});
    return {ok:true,json:async () => opts.method === 'POST' ? {ok:true,n:1,bad:['unknown 900']} : {homework:{id:'h1',courseId:'c1',mode:'manual',published:true,submitted:1,total:2}}};
  };
  vm.runInContext(`detail = {id:'h1',courseId:'c1'};`, ctx);
  element('hwScores').value = 'a 88 补\nunknown 900';
  await vm.runInContext(`saveScores({preventDefault(){}})`, ctx);
  assert.equal(element('hwScores').value, 'a 88 补\nunknown 900');
  assert.match(element('hwScoreMessage').textContent, /unknown 900/);
  assert.match(element('hwCounts').innerHTML, /已录/);
  assert.equal(requests[0].url, '/api/homework/h1/scores');
  assert.deepEqual(JSON.parse(requests[0].opts.body), {text:'a 88 补\nunknown 900'});
  assert.equal(element('hwSaveScores').disabled, false);
  ctx.fetch = async () => {throw Error('offline');};
  await vm.runInContext(`saveScores({preventDefault(){}})`, ctx);
  assert.equal(element('hwScores').value, 'a 88 补\nunknown 900');
  assert.match(element('hwScoreMessage').textContent, /offline/);
  assert.equal(element('hwSaveScores').disabled, false);
  ctx.fetch = async () => ({ok:true,json:async () => ({homework:{id:'legacy',courseId:'c1',name:'Legacy',due:'11/28',mode:'manual',scores:{}}})});
  await vm.runInContext(`renderDetail('legacy')`, ctx);
  assert.match(element('hwRoot').innerHTML, /type="text" id="hwDue" value="11\/28"/);
  assert.match(element('hwRoot').innerHTML, /id="hwScores" rows="6"/);
  element('hwName').value = 'Rename only'; element('hwDue').value = '11/28';
  ctx.fetch = async (url, opts) => { assert.deepEqual(JSON.parse(opts.body),{name:'Rename only',due:'11/28'}); return {ok:true,json:async () => ({ok:true})}; };
  await vm.runInContext(`saveInfo({preventDefault(){}})`, ctx);
  assert.match(element('hwInfoMessage').textContent, /已保存/);
  const beforeModal=element('hwRoot').innerHTML;
  vm.runInContext("courses=[{id:'c1',name:'Course'}];renderNew()",ctx);
  assert.equal(element('hwRoot').innerHTML,beforeModal,'opening must preserve the list behind the modal');
  assert.equal(element('hwCreateDialog').open,true);
  assert.match(element('hwCreateDialog').innerHTML,/hwCreateCancel/);
  assert.doesNotMatch(element('hwCreateDialog').innerHTML,/hwQuestions|hwPass|hwScale|hwMode|批改设置/);
  element('hwCourse').value='c1';element('hwName').value='New';element('hwDue').value='2026-11-01';
  ctx.fetch=async()=>{throw Error('offline')};
  await vm.runInContext('createHomework({preventDefault(){}})',ctx);
  assert.equal(element('hwCreateDialog').open,true);assert.equal(element('hwName').value,'New');assert.equal(element('hwDue').value,'2026-11-01');assert.equal(element('hwCreate').disabled,false);assert.match(element('hwCreateMessage').textContent,/offline/);
  ctx.fetch=async(url,opts)=>{assert.deepEqual(JSON.parse(opts.body),{courseId:'c1',name:'New',due:'2026-11-01'});return {ok:true,json:async()=>({ok:true,id:'new-id'})}};
  await vm.runInContext('createHomework({preventDefault(){}})',ctx);assert.equal(ctx.location.href,'/homework?id=new-id');
  vm.runInContext("detail={id:'h1',name:'New',due:'',batchId:'g1',scores:{}};scoreHasErrors=false",ctx);
  element('hwName').value='New';element('hwDue').value='';element('hwScores').value='s1 未交';
  ctx.fetch=async(url,opts)=>({ok:true,json:async()=>url.endsWith('/scores')?{ok:true,n:1,bad:[]}:{homework:{id:'h1',name:'New',due:'',batchId:'g1',scores:{},published:true}}});
  await vm.runInContext('saveScores({preventDefault(){}})',ctx);ctx.location.href='';await vm.runInContext('enableGrading()',ctx);assert.equal(ctx.location.href,'/grading?id=g1','saved missing marker must not block grading');
  console.log('homework page: syntax, escaping, late/zero scores, safe URLs, partial-save feedback, network retention, metadata-only creation and saved-score dirty guard passed');
}
main().catch(error => {console.error(error);process.exitCode=1;});
